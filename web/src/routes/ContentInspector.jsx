import { useParams, Link } from 'react-router-dom';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { PublicationCard } from './Publishing';
import { useTranslation } from 'react-i18next';
import { api, ApiError } from '../lib/api';
import StatusBadge from '../components/StatusBadge';
import PriorityBadge, { CategoryBadge } from '../components/PriorityBadge';

const DEDUP_LABEL = {
  unique: 'First report',
  duplicate: 'Duplicate',
  update: 'Update (new details)',
  legacy: '—',
  pending: 'Checking duplicates',
};

// Every channel that carried this story, in Telegram time order — dedup
// attaches reports to a story but never discards their provenance.
function StorySection({ data }) {
  const story = data.story;
  if (!story || story.reports.length < 2) return null;
  return (
    <section className="mb-4 rounded border border-border bg-panel p-4">
      <h2 className="mb-2 font-mono text-xs uppercase tracking-wide text-text-muted">
        Story reported by {story.item_count} source{story.item_count === 1 ? '' : 's'}
        {story.update_count > 0 && ` · ${story.update_count} update${story.update_count === 1 ? '' : 's'}`}
      </h2>
      <ul className="space-y-1 text-sm">
        {story.reports.map((r) => (
          <li key={r.id} className="flex flex-wrap items-center gap-2 font-mono text-xs text-text-muted">
            <span>{new Date(r.telegram_date).toLocaleString()}</span>
            {r.id === data.id ? (
              <span className="text-text">@{r.channel_username} (this post)</span>
            ) : (
              <Link to={`/content/${r.id}`} className="text-accent hover:underline">
                @{r.channel_username}
              </Link>
            )}
            <span>{DEDUP_LABEL[r.dedup_status] || r.dedup_status}</span>
            {r.dedup_method && (
              <span>
                via {r.dedup_method}
                {r.dedup_score != null && ` (${Number(r.dedup_score).toFixed(2)})`}
              </span>
            )}
            <a href={r.message_url} target="_blank" rel="noreferrer noopener" className="hover:underline">
              t.me ↗
            </a>
          </li>
        ))}
      </ul>
    </section>
  );
}

function TranslationSection({ data }) {
  if (!data.translation_status || data.translation_status === 'pending') {
    return (
      <section className="mb-4 rounded border border-border bg-panel p-4 text-sm text-text-muted">
        Translation pending — not yet processed by the pipeline.
      </section>
    );
  }

  if (data.translation_status === 'skipped_same_language') {
    return (
      <section className="mb-4 rounded border border-border bg-panel p-4 text-sm text-text-muted">
        No translation needed (source already in {data.target_language || 'English'}, or no text
        to translate).
      </section>
    );
  }

  if (data.translation_status === 'failed') {
    return (
      <section className="mb-4 rounded border border-priority-high/50 bg-panel p-4">
        <h2 className="mb-2 font-mono text-xs uppercase tracking-wide text-priority-high">
          Translation failed
        </h2>
        <p className="text-sm text-text-muted">{data.translation_error}</p>
        <p className="mt-2 text-xs text-text-muted">
          Attempt {data.translation_attempts} of 5 — the original text above is unaffected;
          translation retries automatically without re-fetching from Telegram.
        </p>
      </section>
    );
  }

  return (
    <section className="mb-4 rounded border border-accent/40 bg-panel p-4">
      <h2 className="mb-2 flex items-center gap-2 font-mono text-xs uppercase tracking-wide text-accent">
        Automated translation
        {data.source_language && (
          <span className="rounded border border-border px-1.5 py-0.5 text-text-muted normal-case">
            {data.source_language} → {data.target_language || 'en'}
          </span>
        )}
      </h2>
      <p className="whitespace-pre-wrap text-sm text-text">{data.translated_text}</p>
      <p className="mt-2 text-xs text-text-muted">
        Generated by {data.translation_model || 'an automated model'} — not a verified human
        translation.
      </p>
    </section>
  );
}

function ClassificationSection({ data }) {
  if (data.status === 'failed_tagging') {
    return (
      <section className="mb-4 rounded border border-priority-high/50 bg-panel p-4">
        <h2 className="mb-2 font-mono text-xs uppercase tracking-wide text-priority-high">
          Classification failed
        </h2>
        <p className="text-xs text-text-muted">
          Attempt {data.tagging_attempts} of 5 — retries automatically; the item still appears in
          the feed in the meantime.
        </p>
      </section>
    );
  }

  if (!['ready'].includes(data.status)) {
    return (
      <section className="mb-4 rounded border border-border bg-panel p-4 text-sm text-text-muted">
        Classification pending — not yet processed by the pipeline.
      </section>
    );
  }

  return (
    <section className="mb-4 rounded border border-border bg-panel p-4">
      <h2 className="mb-2 font-mono text-xs uppercase tracking-wide text-text-muted">
        Automated classification
      </h2>
      <div className="mb-2 flex flex-wrap items-center gap-1.5">
        <CategoryBadge category={data.category} />
        <PriorityBadge priority={data.priority} />
        {!data.category && !data.priority && (
          <span className="text-sm text-text-muted">No category matched.</span>
        )}
      </div>
      {data.tags?.length > 0 && (
        <div className="flex flex-wrap gap-1.5">
          {data.tags.map((tag) => (
            <span
              key={tag.name}
              className="rounded border border-border px-1.5 py-0.5 font-mono text-xs text-text-muted"
            >
              {tag.name}
            </span>
          ))}
        </div>
      )}
      <p className="mt-2 text-xs text-text-muted">
        Rule-based classification — deterministic keyword matching, not a verified human
        assessment.
      </p>
    </section>
  );
}

// "Draft drawer": this post's version for each of the operator's channels —
// request drafts, then approve (bot channel) or copy + mark as sent (manual).
function ChannelDrafts({ itemId }) {
  const { t } = useTranslation();
  const queryClient = useQueryClient();
  const variants = useQuery({
    queryKey: ['publications', 'item', itemId],
    queryFn: () => api.publicationsForItem(itemId),
    refetchInterval: (q) => (q.state.data?.items.some((p) => ['requested', 'drafting'].includes(p.status)) ? 3000 : false),
  });
  const request = useMutation({
    mutationFn: () => api.requestDraft(itemId),
    onSuccess: () => queryClient.invalidateQueries({ queryKey: ['publications', 'item', itemId] }),
  });
  const items = variants.data?.items || [];
  return (
    <section className="mb-4 rounded border border-border bg-panel">
      <div className="flex items-center justify-between px-4 py-2">
        <h2 className="font-mono text-xs uppercase tracking-wide text-text-muted">{t('publishing.forMyChannels')}</h2>
        <button
          onClick={() => request.mutate()}
          disabled={request.isPending}
          className="rounded border border-accent px-2 py-1 text-xs text-accent hover:bg-accent/10 disabled:opacity-50"
        >
          {items.length ? t('publishing.draftMissing') : t('publishing.draftPost')}
        </button>
      </div>
      {request.isError && <p className="px-4 pb-2 text-xs text-priority-high">{request.error.message}</p>}
      {items.map((pub) => (
        <PublicationCard key={pub.id} pub={pub} t={t} compact />
      ))}
    </section>
  );
}

export default function ContentInspector() {
  const { id } = useParams();
  const { data, isLoading, isError, error } = useQuery({
    queryKey: ['item', id],
    queryFn: () => api.item(id),
  });

  if (isLoading) return <div className="p-6 text-sm text-text-muted">Loading item…</div>;

  if (isError) {
    const notFound = error instanceof ApiError && error.status === 404;
    return (
      <div className="p-6 text-sm text-priority-high">
        {notFound ? 'Item not found.' : 'Could not load this item.'}
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-2xl p-6">
      <Link to="/dashboard" className="mb-4 inline-block text-sm text-accent underline">
        <span className="inline-block rtl:-scale-x-100">←</span> Back to feed
      </Link>

      <div className="mb-4 flex items-center justify-between">
        <Link to={`/sources/${data.source_id}`} className="font-mono text-base text-text hover:text-accent">
          {data.display_name} · @{data.channel_username}
        </Link>
        <StatusBadge status={data.status} />
      </div>

      <dl className="mb-4 grid grid-cols-2 gap-y-1 text-xs text-text-muted">
        <dt>Telegram message ID</dt>
        <dd className="text-right text-text">{data.telegram_message_id}</dd>
        <dt>Original timestamp</dt>
        <dd className="text-right text-text">{new Date(data.telegram_date).toLocaleString()}</dd>
        <dt>Collected at</dt>
        <dd className="text-right text-text">{new Date(data.collected_at).toLocaleString()}</dd>
        <dt>Has media</dt>
        <dd className="text-right text-text">{data.has_media ? 'Yes' : 'No'}</dd>
        <dt>Original post</dt>
        <dd className="text-right text-text">
          <a href={data.message_url} target="_blank" rel="noreferrer noopener" className="text-accent hover:underline">
            {data.message_url}
          </a>
        </dd>
      </dl>

      <section className="mb-4 rounded border border-border bg-panel p-4">
        <h2 className="mb-2 font-mono text-xs uppercase tracking-wide text-text-muted">
          Original source text
        </h2>
        <p className="whitespace-pre-wrap text-sm text-text">
          {data.raw_text || <span className="italic text-text-muted">No text (media-only post)</span>}
        </p>
      </section>

      <StorySection data={data} />

      <ChannelDrafts itemId={data.id} />

      <TranslationSection data={data} />

      <ClassificationSection data={data} />

      {data.raw_metadata && Object.keys(data.raw_metadata).length > 0 && (
        <details className="rounded border border-border bg-panel p-4">
          <summary className="cursor-pointer font-mono text-xs uppercase tracking-wide text-text-muted">
            Raw Telegram metadata
          </summary>
          <pre className="mt-2 overflow-x-auto whitespace-pre-wrap break-all text-xs text-text-muted">
            {JSON.stringify(data.raw_metadata, null, 2)}
          </pre>
        </details>
      )}
    </div>
  );
}
